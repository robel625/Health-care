export const SYMPTOM_NAMES: string[] = SYMPTOMS_CATALOG.map((s) => s.name);

export const SYMPTOM_URL_MAP: Record<string, string> = Object.fromEntries(
  SYMPTOMS_CATALOG.map((s) => [s.name.toLowerCase().trim(), s.url])
);

const CUSTOM_SYMPTOMS_KEY = "healthcare_custom_symptoms_v1";

function loadCustomSymptoms(): SymptomEntry[] {
  try {
    const raw = typeof window !== "undefined" ? localStorage.getItem(CUSTOM_SYMPTOMS_KEY) : null;
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

function saveCustomSymptoms(list: SymptomEntry[]) {
  try {
    if (typeof window !== "undefined") {
      localStorage.setItem(CUSTOM_SYMPTOMS_KEY, JSON.stringify(list));
    }
  } catch {
    // Ignore storage errors
  }
}

// Hydrate stored custom symptoms into URL map and custom storage
const storedCustom = loadCustomSymptoms();
for (const item of storedCustom) {
  const normalized = item.name.trim();
  if (item.url) {
    SYMPTOM_URL_MAP[normalized.toLowerCase()] = item.url;
  }
}

export function registerCustomSymptom(name: string, url?: string): SymptomEntry {
  const trimmed = name.trim();
  const letter = (trimmed[0] || "A").toUpperCase();
  const entry: SymptomEntry = {
    name: trimmed,
    url: url?.trim() || "",
    letter,
  };

  const key = trimmed.toLowerCase();
  if (entry.url) {
    SYMPTOM_URL_MAP[key] = entry.url;
  }

  const current = loadCustomSymptoms().filter((s) => s.name.toLowerCase() !== key);
  current.push(entry);
  saveCustomSymptoms(current);

  return entry;
}

export function getCustomSymptoms(): SymptomEntry[] {
  return loadCustomSymptoms();
}

export function getSymptomUrl(name: string): string | undefined {
  if (!name) return undefined;
  return SYMPTOM_URL_MAP[name.toLowerCase().trim()];
}
